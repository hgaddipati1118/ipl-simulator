"""
Export the CricketArchive T20 age curves (data/analysis/ca_age_curves.csv) as a small table the engine imports:
packages/engine/src/age-curves.ts, rating points per season by gender, curve (bat / pace / spin) and age.

A curve's `delta` is the expected change in runs per 100 balls from one season to the next at that age
(delta method, centred, see ca-ratings.py). It becomes rating points the way the CA ratings map to 0-99:
points = 11 * delta / (sd * r), where sd is the spread of ratings among that year's regulars (mean over 2021-2026)
and r is the mean reliability B / (B + K) of the season pairs behind the curve: the curves are fitted on shrunk
season values, which damps a real change by about r, so dividing by r restores delta-method size. r is floored
at R_FLOOR (bowling reliabilities of 0.13-0.16 would multiply noise by 6-8x), and women's curves are averaged with
the men's curve of the same kind because women's season pairs are thin.
Batting attributes follow the all-batters curve; bowling attributes follow the pace or spin curve.
Run from packages/ratings:  python3 -I src/analysis/export-age-curves.py
"""
import csv, math, subprocess
from collections import defaultdict
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
OUT = ROOT.parent / "engine" / "src" / "age-curves.ts"
AGES = list(range(16, 43))
MAX_STEP = 3.0  # points per season; the noisiest old-age cells can't swing more than this
R_FLOOR = 0.3
WOMEN_OWN_WEIGHT = 0.5
REG = 120       # T20 balls in a year to count as a regular (same as ca-ratings.py)


def spread(gender, side):
    out = subprocess.run(["duckdb", "-csv", "-noheader", "-c",
                          f"SELECT avg(sd) FROM (SELECT year, stddev_samp({side}_rating) sd FROM '{ROOT}/data/analysis/ca_ratings_by_year.parquet' "
                          f"WHERE format = 'T20' AND gender = '{gender}' AND {side}_balls >= {REG} AND year BETWEEN 2021 AND 2026 GROUP BY year)"],
                         capture_output=True, text=True, check=True)
    return float(out.stdout.strip())


def reliability(gender, side):
    import json
    K = json.load(open(ROOT / "data" / "analysis" / "ca_validation.json"))[f"{side}/T20/{gender}"]["params"]["K"]
    out = subprocess.run(["duckdb", "-csv", "-noheader", "-c",
                          f"WITH s AS (SELECT player_id, year, {side}_balls b FROM '{ROOT}/data/analysis/ca_ratings_by_year.parquet' "
                          f"WHERE format = 'T20' AND gender = '{gender}' AND {side}_balls >= 60), "
                          f"p AS (SELECT a.b b0, n.b b1, 2*a.b*n.b/(a.b+n.b) w FROM s a JOIN s n ON n.player_id = a.player_id AND n.year = a.year + 1) "
                          f"SELECT sum(w * 0.5 * (b0/(b0+{K}) + b1/(b1+{K}))) / sum(w) FROM p"],
                         capture_output=True, text=True, check=True)
    return float(out.stdout.strip()), K


def main():
    rows = defaultdict(dict)
    for r in csv.DictReader(open(ROOT / "data" / "analysis" / "ca_age_curves.csv")):
        if r["format"] == "T20":
            rows[(r["gender"], r["side"], r["role"])][int(r["age"])] = float(r["delta"])
    table = {}
    for gender in ("male", "female"):
        sds = {"bat": spread(gender, "bat"), "bowl": spread(gender, "bowl")}
        rel = {side: reliability(gender, side) for side in ("bat", "bowl")}
        print(gender, "reliability (r, K):", rel)
        curves = {"bat": ("bat", "all"), "pace": ("bowl", "pace"), "spin": ("bowl", "spin")}
        g = {}
        for name, (side, role) in curves.items():
            d = rows.get((gender, side, role)) or rows[(gender, side, "all")]
            g[name] = [11 * d.get(a, 0.0) / (sds[side] * max(R_FLOOR, rel[side][0])) for a in AGES]
        if gender == "female":
            g = {k: [WOMEN_OWN_WEIGHT * v + (1 - WOMEN_OWN_WEIGHT) * m for v, m in zip(g[k], table["male"][k])] for k in g}
        table[gender] = g
        table[gender + "_sd"] = sds
    for gender in ("male", "female"):
        for k in table[gender]:
            table[gender][k] = [round(max(-MAX_STEP, min(MAX_STEP, v)), 2) for v in table[gender][k]]
    lines = [
        "// Generated by packages/ratings/src/analysis/export-age-curves.py from the CricketArchive T20 age curves",
        "// (data/analysis/ca_age_curves.csv). Do not edit by hand; re-run the script.",
        "//",
        "// Expected rating change (points) from one season to the next, by the age the player turns, for batting",
        "// attributes (`bat`) and bowling attributes (`pace` / `spin`). Centred delta method on league-relative values,",
        "// so the curves are zero-sum across a league: young players rise, older ones fall.",
        "",
        f"export const AGE_CURVE_FIRST_AGE = {AGES[0]};",
        f"export const AGE_CURVE_LAST_AGE = {AGES[-1]};",
        "",
        "export type AgeCurveGender = \"male\" | \"female\";",
        "export type AgeCurveKind = \"bat\" | \"pace\" | \"spin\";",
        "",
        "export const AGE_CURVES: Record<AgeCurveGender, Record<AgeCurveKind, readonly number[]>> = {",
    ]
    for gender in ("male", "female"):
        lines.append(f"  {gender}: {{")
        for name in ("bat", "pace", "spin"):
            lines.append(f"    {name}: [{', '.join(str(v) for v in table[gender][name])}],")
        lines.append("  },")
    lines += [
        "};",
        "",
        "/** Expected change when a player goes from `age - 1` to `age` (clamped to the table's ages) */",
        "export function ageCurveDelta(gender: AgeCurveGender, kind: AgeCurveKind, age: number): number {",
        "  const i = Math.max(AGE_CURVE_FIRST_AGE, Math.min(AGE_CURVE_LAST_AGE, Math.round(age) - 1)) - AGE_CURVE_FIRST_AGE;",
        "  return AGE_CURVES[gender][kind][i];",
        "}",
        "",
    ]
    OUT.write_text("\n".join(lines))
    print("wrote", OUT)
    for gender in ("male", "female"):
        for name in ("bat", "pace", "spin"):
            v = table[gender][name]
            cum, best, peak = 0.0, -1e9, None
            for a, d in zip(AGES, v):
                if cum > best:
                    best, peak = cum, a
                cum += d
            print(f"{gender:6} {name:4} sd={table[gender + '_sd']['bat' if name == 'bat' else 'bowl']:.1f} peak~{peak} "
                  f"18->22 {sum(v[2:6]):+.1f}  22->28 {sum(v[6:12]):+.1f}  28->34 {sum(v[12:18]):+.1f}  34->38 {sum(v[18:22]):+.1f}")


if __name__ == "__main__":
    main()
