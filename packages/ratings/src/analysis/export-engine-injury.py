"""
Trim data-export/injury-risk.json into the engine's injury table (packages/engine/src/injury-data.ts).

Adds a per-type tilt toward the IPL replacement record (docs/INJURY-RISK-REPORT.md section 4), an
independent signal of real injuries, shrunk by how many replacements each type has (w = n / (n + 20)).
The overall scale (real injuries vs all absences) is set in injury.ts from season benchmarks.

Run from packages/ratings:  python3 -I src/analysis/export-engine-injury.py
"""
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
SRC = ROOT / "data-export" / "injury-risk.json"
OUT = ROOT.parent / "engine" / "src" / "injury-data.ts"

# IPL squad-seasons ending in a replacement: (replaced, squad-seasons). Express and fast-medium
# are pooled because the game's pace styles can't be split the way CricketArchive labels them.
REPLACEMENTS = {
    "pace": (26 + 55, 125 + 718),
    "medium": (11, 269),
    "wrist spin": (10, 226),
    "finger spin": (4, 347),
    "batter": (38, 928),
    "bowling all-rounder": (15, 239),
    "batting all-rounder": (18, 421),
    "wicketkeeper": (15, 360),
}
SHRINK_N = 20


def main():
    d = json.loads(SRC.read_text())
    base = d["base_per_match_by_archetype_and_age"]
    bands = list(base["batter"].keys())
    ex, fm = base["express/fast"], base["fast-medium"]
    n_ex, n_fm = 125, 718
    table = {"pace": {b: (ex[b] * n_ex + fm[b] * n_fm) / (n_ex + n_fm) for b in bands}}
    for k in ["medium", "wrist spin", "finger spin", "batter", "bowling all-rounder", "batting all-rounder", "wicketkeeper"]:
        table[k] = dict(base[k])

    total = sum(s for _, s in REPLACEMENTS.values())
    pooled_rate = sum(n for n, _ in REPLACEMENTS.values()) / total
    model_mean = sum(table[k]["27-30"] * s for k, (_, s) in REPLACEMENTS.items()) / total
    tilt = {}
    for k, (n, s) in REPLACEMENTS.items():
        w = n / (n + SHRINK_N)
        tilt[k] = ((n / s / pooled_rate) / (table[k]["27-30"] / model_mean)) ** w

    out = {
        "bands": bands,
        "base": {k: {b: round(v, 5) for b, v in t.items()} for k, t in table.items()},
        "tilt": {k: round(v, 3) for k, v in tilt.items()},
        "previousInjury": d["previous_injury_multiplier"],
        "women": d["women_multiplier"],
        "format": d["format_multiplier"],
        "duration": d["matches_missed_distribution"],
        "replacementRate": {k: round(n / s, 4) for k, (n, s) in REPLACEMENTS.items()},
    }
    ts = (
        "/**\n"
        " * GENERATED by packages/ratings/src/analysis/export-engine-injury.py from\n"
        " * packages/ratings/data-export/injury-risk.json. Do not edit by hand.\n"
        " *\n"
        " * base: per-match chance a regular starts an absence after a match (T20 men 2018+, confirmed +\n"
        " * likely evidence; includes some rest/rotation, scaled down in injury.ts). tilt: per-type nudge\n"
        " * toward the IPL replacement record, shrunk by sample size. duration: share of absences lasting\n"
        " * 1-2 / 3-5 / 6+ matches.\n"
        " */\n"
        f"export const INJURY_DATA = {json.dumps(out, indent=1)} as const;\n"
    )
    OUT.write_text(ts)
    print(f"wrote {OUT} ({len(ts)} bytes)")
    for k in table:
        print(f"  {k:20} 27-30 {table[k]['27-30']:.4f} tilt {tilt[k]:.2f}")


if __name__ == "__main__":
    main()
