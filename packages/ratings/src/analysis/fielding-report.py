"""
Report + sanity checks for the fielding / keeping ratings (src/analysis/fielding-ratings.py).
Writes data/analysis/fielding-report.md (snapshot: docs/FIELDING-REPORT.md) and exits 1 if a sanity check fails.
Run from packages/ratings:  python3 -I src/analysis/fielding-report.py
"""
import csv, json, subprocess, sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
DATA = ROOT / "data" / "analysis"


def duck(sql):
    out = subprocess.run(["duckdb", "-csv", "-nullvalue", "", "-c", sql], capture_output=True, text=True, cwd=ROOT)
    if out.returncode:
        sys.exit(out.stderr)
    return list(csv.DictReader(out.stdout.splitlines()))


def table(rows, cols):
    head = "| " + " | ".join(cols) + " |\n|" + "|".join("---" for _ in cols) + "|\n"
    return head + "\n".join("| " + " | ".join(str(r[c]) for c in cols) + " |" for r in rows) + "\n"


def main():
    val = json.load(open(DATA / "fielding_validation.json"))
    F = "data/analysis/fielding_ratings.csv"
    link = duck("SELECT source, count(*) n FROM 'data/analysis/keeper_match_map.parquet' GROUP BY 1 ORDER BY 2 DESC")
    total_tm = sum(int(r["n"]) for r in link)
    md = ["# Fielding and wicketkeeping ratings", "",
          "Generated by `src/analysis/fielding-report.py` from `fielding_ratings.csv`. Method: `docs/RATINGS-PIPELINE.md` (Fielding and keeping).", ""]
    md.append("## Data\n")
    md.append("Cricsheet T20 + IT20 ball-by-ball, men and women, 2005 on; the wicketkeeper of each side comes from the CricketArchive scorecard keeper flag "
              "(Cricsheet match linked by date and player names). Keeper identified per team-match: " +
              ", ".join(f"{r['source']} {int(r['n']):,} ({int(r['n']) / total_tm:.0%})" for r in link) + ". Rates use only the CA-flagged keepers' innings.\n")
    for g in ("male", "female"):
        c, k = val[g]["catching"], val[g]["keeping"]
        md.append(f"### {g}\n")
        md.append(f"- Catching: {c['players']:,} fielders, {c['innings']:,} fielder-innings, {c['catches_per_innings_per_fielder']:.3f} catches per fielder-innings; "
                  f"fitted prior k = {c['k']:.1f} (SD of true catching skill ~{c['true_sd_log']:.0%}); split-half correlation of catch ratio across odd/even matches "
                  f"{c['split_half']['corr_raw']:.2f} raw ({c['split_half']['players']} players with 40+ innings each half). Bowling-load classes (catches per chance vs the mean): "
                  + ", ".join(f"{k_} {v:.2f}" for k_, v in c["class_ratio"].items()) + "; half the gap is kept in the rating.")
        md.append(f"- Keeping: {k['keepers']:,} keepers, {k['innings']:,} keeper-innings. Observed / expected: stumpings {k['st']['observed']:.0f} / {k['st']['expected']:.0f}, "
                  f"keeper catches {k['kc']['observed']:.0f} / {k['kc']['expected']:.0f}, bye events {k['bye']['observed']:.0f} / {k['bye']['expected']:.0f}. "
                  f"Prior SD of true skill (log ratio): stumpings {k['st']['true_sd_log']:.2f}, catches {k['kc']['true_sd_log']:.2f}, byes {k['bye']['true_sd_log']:.2f}. "
                  f"Split-half correlations (25+ keeper innings each half, {k['split_half']['byes']['players']} keepers): stumpings {k['split_half']['stumpings']['corr_raw']:.2f}, "
                  f"keeper catches {k['split_half']['keeper_catches']['corr_raw']:.2f}, byes {k['split_half']['byes']['corr_raw']:.2f}.\n")

    checks = []
    for g, label in (("male", "Men"), ("female", "Women")):
        rows = duck(f"""SELECT name, round(field_inns) AS inns, round(catches) AS catches, round(exp_catches, 1) AS expected, catch_ratio AS ratio, ro_involved AS runouts, fielding
                        FROM '{F}' WHERE gender = '{g}' AND catch_inns >= 100 ORDER BY fielding DESC, catch_inns DESC LIMIT 15""")
        md.append(f"## {label}: top fielders (100+ innings in the field)\n")
        md.append(table(rows, ["name", "inns", "catches", "expected", "ratio", "runouts", "fielding"]))
        rows = duck(f"""SELECT name, round(field_inns) AS inns, round(catches) AS catches, round(exp_catches, 1) AS expected, catch_ratio AS ratio, fielding
                        FROM '{F}' WHERE gender = '{g}' AND catch_inns >= 100 ORDER BY fielding ASC, catch_inns DESC LIMIT 8""")
        md.append(f"{label}: lowest\n")
        md.append(table(rows, ["name", "inns", "catches", "expected", "ratio", "fielding"]))
        rows = duck(f"""SELECT name, keep_inns AS keeper_inns, st, round(exp_st, 1) AS exp_st, kc AS catches, round(exp_kc, 1) AS exp_catches, bye_ev AS byes, round(exp_bye, 1) AS exp_byes, keeping
                        FROM '{F}' WHERE gender = '{g}' AND keep_inns >= 100 ORDER BY keeping DESC LIMIT 10""")
        md.append(f"## {label}: top keepers (100+ keeper innings)\n")
        md.append(table(rows, ["name", "keeper_inns", "st", "exp_st", "catches", "exp_catches", "byes", "exp_byes", "keeping"]))
        rows = duck(f"""SELECT name, keep_inns AS keeper_inns, st, round(exp_st, 1) AS exp_st, kc AS catches, round(exp_kc, 1) AS exp_catches, bye_ev AS byes, round(exp_bye, 1) AS exp_byes, keeping
                        FROM '{F}' WHERE gender = '{g}' AND keep_inns >= 100 ORDER BY keeping ASC LIMIT 5""")
        md.append(f"{label}: lowest\n")
        md.append(table(rows, ["name", "keeper_inns", "st", "exp_st", "catches", "exp_catches", "byes", "exp_byes", "keeping"]))

        s = duck(f"""SELECT avg(fielding) m_f, stddev(fielding) sd_f, count(*) n FROM '{F}' WHERE gender = '{g}' AND catch_inns >= 100""")[0]
        k = duck(f"""SELECT avg(keeping) m_k, stddev(keeping) sd_k, count(*) n FROM '{F}' WHERE gender = '{g}' AND keep_inns >= 100""")[0]
        md.append(f"{label} regulars: fielding mean {float(s['m_f']):.1f}, SD {float(s['sd_f']):.1f} (n={s['n']}); keeping mean {float(k['m_k']):.1f}, SD {float(k['sd_k']):.1f} (n={k['n']}).\n")
        checks.append((f"{label}: regular fielders average near 50", 45 <= float(s["m_f"]) <= 56))
        checks.append((f"{label}: fielding spread is a sensible size", 6 <= float(s["sd_f"]) <= 20))
        checks.append((f"{label}: keepers average near 50", 44 <= float(k["m_k"]) <= 62))
        checks.append((f"{label}: catching is persistent (split-half > 0.4)", (val[g]["catching"]["split_half"]["corr_raw"] or 0) > 0.4))
    men_top = [r["name"] for r in duck(f"""SELECT name FROM '{F}' WHERE gender = 'male' AND catch_inns >= 100 ORDER BY fielding DESC LIMIT 60""")]
    men_bot = [r["name"] for r in duck(f"""SELECT name FROM '{F}' WHERE gender = 'male' AND catch_inns >= 100 ORDER BY fielding ASC LIMIT 60""")]
    checks.append(("Men: de Villiers, Bravo, Stokes, Miller in the top 60 of 100+ innings fielders", all(n in men_top for n in ("AB de Villiers", "DJ Bravo", "BA Stokes", "DA Miller"))))
    checks.append(("Men: Bumrah, Zampa, Shamsi in the bottom 60", all(n in men_bot for n in ("JJ Bumrah", "A Zampa", "T Shamsi"))))
    dk = duck(f"""SELECT keeping FROM '{F}' WHERE name = 'MS Dhoni' AND gender = 'male'""")
    checks.append(("Dhoni keeps at 60+", bool(dk) and int(dk[0]["keeping"]) >= 60))
    checks.append(("Keeper identified in 85%+ of team-matches", sum(int(r["n"]) for r in link if r["source"] != "unknown") / total_tm >= 0.85))

    md.append("## Caveats\n")
    md.append("- Fielding is catches per chance the side created, plus run-out involvement. Position is not observed: fine-leg / third-man bowlers and slip fielders are not separated "
              "(bowlers are compared with bowlers and half of the class gap is kept), so a rating mixes skill with where a player is usually posted.")
    md.append("- Byes are the best-measured keeping component, but how they are scored differs by competition (event-season factors absorb most of it); a keeper with a short career in one "
              "league with unusually few recorded byes (e.g. Nurul Hasan) can rate higher than his reputation. Stumpings and catches behind are mostly bowler-driven; their split-half "
              "reliability is low, so they move a keeper's rating little.")
    md.append("- Players with a thin record sit near 50 (shrinkage); only players with 100+ innings are listed above.\n")
    md.append("## Sanity checks\n")
    for name, ok in checks:
        md.append(f"- {'PASS' if ok else 'FAIL'}: {name}")
    md.append("")
    (DATA / "fielding-report.md").write_text("\n".join(md))
    print("\n".join(md[-(len(checks) + 3):]))
    if not all(ok for _, ok in checks):
        sys.exit(1)


if __name__ == "__main__":
    main()
