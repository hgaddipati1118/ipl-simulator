// Regenerate src/sdk-context.ts from packages/mods: the SDK's public .d.ts and the example mods.
// This is the context the generator model writes mods against, so rerun it whenever the SDK changes.
// Usage (from packages/server): npm run context   (regenerate packages/mods/sdk first if the SDK changed)

import { existsSync, readdirSync, readFileSync, statSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const modsDir = join(here, "../../mods");
const out = join(here, "../src/sdk-context.ts");

// sdk/index.d.ts is the standalone public surface (npm run sdk --workspace=packages/mods)
const typesPath = [join(modsDir, "sdk/index.d.ts")].find(existsSync);
if (!typesPath) {
  console.error(`No SDK types found under ${modsDir} (run npm run sdk --workspace=packages/mods)`);
  process.exit(1);
}

const examplesDir = join(modsDir, "examples");
const examples = [];
if (existsSync(examplesDir)) {
  for (const name of readdirSync(examplesDir).sort()) {
    const dir = join(examplesDir, name);
    if (!statSync(dir).isDirectory()) continue;
    const files = readdirSync(dir).sort().map(f => `// ${name}/${f}\n${readFileSync(join(dir, f), "utf-8")}`);
    examples.push(files.join("\n\n"));
  }
}

const body = `// Generated by scripts/build-sdk-context.mjs from packages/mods; do not edit by hand.
export const SDK_VERSION = "1";
export const SDK_TYPES = ${JSON.stringify(readFileSync(typesPath, "utf-8"))};
export const EXAMPLE_MODS: string[] = ${JSON.stringify(examples, null, 2)};
`;
writeFileSync(out, body);
console.log(`Wrote ${out} (${typesPath}, ${examples.length} examples)`);
